
num1 = int(input("Enter number"))
num2 = int(input("Enter another number"))

result = num1 == num2 #false 
print(f"{result} = {num1} == {num2}")

result = num1 != num2 #true
print(f"{result} = {num1} != {num2}")

result = num1 < num2 #true
print(f"{result} = {num1} < {num2}")

result = num1 > num2 #false
print(f"{result} = {num1} > {num2}")

result = num1 <= num2 #true
print(f"{result} = {num1} <= {num2}")

result = num1 >= num2 #false
print(f"{result} = {num1} >= {num2}")
