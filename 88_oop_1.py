#create class
class Human:
    def walk(self):
        print("I can walk")
    def talk(self):
        print("I can talk")
    def eat(self):
        print("I can eat")

#create object (class type variables)
ram = Human()
ram.walk()
ram.talk()
ram.eat()

shyam = Human()
shyam.walk()
shyam.talk()
shyam.eat()
